const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const file = path.join(__dirname, 'Project.vue')
const source = fs.readFileSync(file, 'utf8')
const importDialog = fs.readFileSync(path.join(__dirname, '..', 'features', 'project', 'components', 'ProjectImportDialog.vue'), 'utf8')
const exportDialog = fs.readFileSync(path.join(__dirname, '..', 'features', 'project', 'components', 'ProjectExportDialog.vue'), 'utf8')

test('工程工具栏以 JSON 配置命名整体导入和导出入口', () => {
  assert.match(source, /importKepProject/)
  assert.match(source, /exportKepProject/)
  assert.match(source, /:title="\$t\('导入 JSON 配置'\)"/)
  assert.match(source, /:title="\$t\('导出 JSON 配置'\)"/)
  assert.match(importDialog, /accept="\.json,application\/json"/)
  assert.match(exportDialog, /projectApi\.exportUrl/)
  assert.doesNotMatch(source, /\$t\('导入 KEPServer JSON'\)/)
  assert.doesNotMatch(source, /\$t\('导出 KEPServer JSON'\)/)
  assert.doesNotMatch(source, /\.igwproj/)
  assert.doesNotMatch(source, /导出工程\(另存为\)/)
  assert.doesNotMatch(source, /打开工程\(导入 \.igwproj\)/)
  assert.doesNotMatch(source, /accept="\.igwproj/)
})

test('KEP 导入显示规模和警告且替换前确认', () => {
  assert.match(importDialog, /preview\.channels/)
  assert.match(importDialog, /preview\.devices/)
  assert.match(importDialog, /preview\.tags/)
  assert.match(importDialog, /preview\.compatibility\.issues/)
  assert.match(importDialog, /inspectImport/)
  assert.match(importDialog, /commitImport/)
  assert.match(importDialog, /替换当前工程/)
})
