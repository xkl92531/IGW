import { afterEach, expect, it, vi } from 'vitest'
import { QuickClientTiming, timingLabel, visibleTimingIds } from './quickClientTiming'
afterEach(() => vi.useRealTimers())
it('bounds virtual viewport plus overscan to 200 tags', () => {
  const rows = Array.from({ length: 10000 }, (_, i) => ({ itemId: String(i) }))
  expect(visibleTimingIds(rows, 500, 510)).toEqual(rows.slice(495, 516).map(r => r.itemId))
  expect(visibleTimingIds(rows, 500, 900)).toHaveLength(200)
})
it('debounces ranges, stops polling and ignores late results after scope change', async () => {
  vi.useFakeTimers()
  let resolve!: (value: any) => void
  const fetcher = vi.fn((_ids: string[], _signal: AbortSignal) => new Promise<any>(done => { resolve = done }))
  const update = vi.fn()
  const timer = new QuickClientTiming(fetcher, update)
  timer.set(['A'], true)
  timer.set(['B'], true)
  await vi.advanceTimersByTimeAsync(150)
  expect(fetcher).toHaveBeenCalledTimes(1)
  expect(fetcher.mock.calls[0]?.[0]).toEqual(['B'])
  timer.set([], false)
  resolve({ items: [{ tagId: 'B' }] })
  await vi.advanceTimersByTimeAsync(10000)
  expect(update).toHaveBeenLastCalledWith([], false)
  expect(fetcher).toHaveBeenCalledTimes(1)
  timer.dispose()
})
it('does not overlap slow requests and clears stale data on failure', async () => {
  vi.useFakeTimers()
  let reject!: (reason: Error) => void
  const fetcher = vi.fn(() => new Promise<any>((_, fail) => { reject = fail }))
  const update = vi.fn()
  const timer = new QuickClientTiming(fetcher, update)
  timer.set(['A'], true)
  await vi.advanceTimersByTimeAsync(10000)
  expect(fetcher).toHaveBeenCalledTimes(1)
  reject(new Error('offline'))
  await vi.advanceTimersByTimeAsync(0)
  expect(update).toHaveBeenLastCalledWith([], true)
  timer.dispose()
})
it('waits for a cancelled request to settle before starting the latest viewport', async () => {
  vi.useFakeTimers()
  const resolvers: ((value: any) => void)[] = []
  const fetcher = vi.fn((_ids: string[], _signal: AbortSignal) => new Promise<any>(done => resolvers.push(done)))
  const update = vi.fn()
  const timer = new QuickClientTiming(fetcher, update)
  timer.set(['A'], true)
  await vi.advanceTimersByTimeAsync(150)
  const signal = fetcher.mock.calls[0]![1]
  timer.set(['B'], true)
  await vi.advanceTimersByTimeAsync(3000)
  expect(signal.aborted).toBe(true)
  expect(fetcher).toHaveBeenCalledTimes(1)
  resolvers[0]!({ items: [{ tagId: 'A' }] })
  await vi.advanceTimersByTimeAsync(150)
  expect(fetcher).toHaveBeenCalledTimes(2)
  expect(fetcher.mock.calls[1]![0]).toEqual(['B'])
  expect(update).toHaveBeenLastCalledWith([], false)
  timer.dispose()
  resolvers[1]!({ items: [] })
})
it('never invents subscription or missing-history duration', () => {
  expect(timingLabel({ mode: 'subscription', batch: null } as any)).toBe('订阅推送')
  expect(timingLabel({ mode: 'polling', batch: null } as any)).toBe('—')
  expect(timingLabel({ mode: 'polling', batch: { totalMs: 12.34 } } as any)).toBe('12.34 ms')
})
