import { describe, expect, it } from 'vitest'
import { createItemIdMapping, mergeGeneratedMapping } from './mesFieldMappingMerge'

const db = { sourcePath: 'PLC6.PLC6.OP051', scope: 'Group' }
const generated = {
  fields: [{ tagId: 'PLC6.PLC6.OP051.Result', fieldName: '' }, { tagId: 'PLC6.PLC6.OP051.Barcode', fieldName: '' }],
  structs: [{ kind: 'Array', countMode: 'Enum', baseGroup: 'PLC6.PLC6.OP051.ShoulderGlue.GlueData', aliasName: 'GlueData',
    startIndex: 1, fixedCount: 2, members: [{ tagId: 'Result', fieldName: '' }, { tagId: 'Position', fieldName: '' }] }],
}

it('fills an empty upload node with the generated fields and structs', () => {
  const payload: any = { fields: [], structs: [] }
  mergeGeneratedMapping(payload, generated, [], [db])
  expect(payload.fields.map((field: any) => field.tagId)).toEqual(['PLC6.PLC6.OP051.Result', 'PLC6.PLC6.OP051.Barcode'])
  expect(payload.structs[0]).toMatchObject({ kind: 'Array', countMode: 'Enum', aliasName: 'GlueData', startIndex: 1, fixedCount: 2 })
})

it('keeps edited names, codes, struct settings and manual fields when the data is configured again', () => {
  const payload: any = {
    fields: [
      { tagId: 'PLC6.PLC6.OP051.Result', fieldName: 'result', parameterCode: 'P01' },
      { tagId: 'PLC6.PLC6.OP051.Old', fieldName: '' },                        // 上次选中、这次没有了
      { tagId: 'PLC6.PLC6.OP099.Manual', fieldName: 'manual' },               // 手工加的，不在任何范围
    ],
    structs: [{ kind: 'Array', countMode: 'Enum', baseGroup: 'PLC6.PLC6.OP051.ShoulderGlue.GlueData', aliasName: 'glueData',
      startIndex: 1, fixedCount: 2, members: [{ tagId: 'Result', fieldName: 'res' }] }],
  }
  mergeGeneratedMapping(payload, generated, [db], [db])
  expect(payload.fields).toEqual([
    { tagId: 'PLC6.PLC6.OP051.Result', fieldName: 'result', parameterCode: 'P01' },
    { tagId: 'PLC6.PLC6.OP099.Manual', fieldName: 'manual' },
    { tagId: 'PLC6.PLC6.OP051.Barcode', fieldName: '' },
  ])
  expect(payload.structs).toHaveLength(1)
  expect(payload.structs[0]).toMatchObject({ aliasName: 'glueData', members: [{ tagId: 'Result', fieldName: 'res' }] })
})

it('removes what was deselected and applies a newly chosen array slice', () => {
  const payload: any = { fields: [], structs: [] }
  mergeGeneratedMapping(payload, generated, [], [db])
  const glue = { sourcePath: 'PLC6.PLC6.OP051.ShoulderGlue.GlueData', scope: 'Array', arrayStart: [2], arrayLengths: [1] }
  mergeGeneratedMapping(payload, { fields: [], structs: [{ ...generated.structs[0], startIndex: 2, fixedCount: 1 }] }, [db], [glue])
  expect(payload.fields).toEqual([])
  expect(payload.structs[0]).toMatchObject({ startIndex: 2, fixedCount: 1 })
})

it('keeps nested structs nested and upgrades a flat struct generated by an older version', () => {
  const nested = { kind: 'Object', baseGroup: 'PLC6.PLC6.OP051.Station', aliasName: 'Station',
    members: [{ tagId: 'Speed', fieldName: '' }],
    structs: [{ kind: 'Object', baseGroup: 'Inner', aliasName: 'Inner', members: [{ tagId: 'X', fieldName: '' }], structs: [] }] }
  const payload: any = { fields: [], structs: [{ kind: 'Object', baseGroup: 'PLC6.PLC6.OP051.Station', aliasName: 'station',
    members: [{ tagId: 'Speed', fieldName: '' }, { tagId: 'Inner.X', fieldName: '' }] }] }
  mergeGeneratedMapping(payload, { fields: [], structs: [nested] }, [db], [db])
  const station = payload.structs[0]
  expect(station.aliasName).toBe('station')                          // 改过的 JSON 字段名保留
  expect(station.members.map((member: any) => member.tagId)).toEqual(['Speed'])
  expect(station.structs[0].members[0].tagId).toBe('X')
  expect(station.structs).not.toBe(nested.structs)                   // 复制，不和生成结果共用
})

describe('item-ID format conversion', () => {
  const group = 'L.P.DB'
  const field = { tagId: 'L.P.DB.T', fieldName: '' }
  const nested = {
    kind: 'Object', baseGroup: 'L.P.DB.S', aliasName: 'S', members: [{ tagId: 'A' }],
    structs: [{ kind: 'Object', baseGroup: 'Inner', aliasName: 'Inner', members: [{ tagId: 'Code' }] }],
  }

  it.each(['List', 'Object', 'Array'])('preserves every existing %s setting without upgrading it', kind => {
    const existing = {
      kind, baseGroup: 'L.P.DB.S', aliasName: 'custom', countMode: 'Tag', countTagId: 'L.P.DB.Count',
      fixedCount: 2, startIndex: 1, members: [{ tagId: 'Inner.Code', fieldName: 'wire', scale: 2, format: 'F2' }],
    }
    const payload = { fields: [], structs: [existing] }
    const result = createItemIdMapping(payload, { fields: [field, { tagId: 'L.P.DB.S.A' }], structs: [nested] }, group)
    expect(result.fields).toEqual([field])
    expect(result.structs).toEqual([existing])
    expect(result.structs[0]).not.toBe(existing)
    expect(payload).toEqual({ fields: [], structs: [existing] })
  })

  it('deduplicates equivalent conversions using the first field alias and metadata', () => {
    const first = { tagId: 'L.P.DB.T', fieldName: 'raw', parameterCode: 'P1' }
    const result = createItemIdMapping({ fields: [first, { ...field, fieldName: 'alias', scale: 1, format: '' }], structs: [] },
      { fields: [field, { tagId: 'L.P.DB.New', fieldName: '' }], structs: [] }, group)
    expect(result.fields).toEqual([first, { tagId: 'L.P.DB.New', fieldName: '' }])
    expect(result.fields[0]).not.toBe(first)
  })

  it.each([{ scale: 2 }, { format: 'F2' }])('rejects different conversions without changing either input: %j', conversion => {
    const payload = { fields: [field, { ...field, ...conversion }], structs: [] }
    const generated = { fields: [field], structs: [] }
    const before = structuredClone({ payload, generated })
    expect(() => createItemIdMapping(payload, generated, group)).toThrow(/转换配置/)
    expect({ payload, generated }).toEqual(before)
  })

  it('retains a manual root and removes cross-group structures without adding covered generated data', () => {
    const root = { kind: 'Object', baseGroup: group, aliasName: 'block', members: [{ tagId: 'T', fieldName: 'reading' }], structs: [{ ...nested, baseGroup: 'S' }] }
    const other = { kind: 'List', baseGroup: 'L.P.DB2', aliasName: 'other', members: [{ tagId: 'T' }] }
    const result = createItemIdMapping({ fields: [field], structs: [root, other] }, { fields: [field], structs: [nested] }, group)
    expect(result).toEqual({ fields: [], structs: [root] })
  })

  it('prunes only branches covered by a manual child while preserving generated siblings', () => {
    const child = { kind: 'List', baseGroup: 'L.P.DB.S.Inner', aliasName: 'codes', members: [{ tagId: 'Code', scale: 2 }] }
    const generated = { fields: [field], structs: [{ ...nested,
      members: [{ tagId: 'A' }, { tagId: 'Inner.Code' }],
      structs: [...nested.structs, { kind: 'Object', baseGroup: 'Other', aliasName: 'Other', members: [{ tagId: 'Value' }] }],
    }] }
    const before = structuredClone(generated)
    const result = createItemIdMapping({ fields: [], structs: [child] }, generated, group)
    expect(result).toEqual({ fields: [field], structs: [child, {
      kind: 'Object', baseGroup: 'L.P.DB.S', aliasName: 'S', members: [{ tagId: 'A' }],
      structs: [{ kind: 'Object', baseGroup: 'Other', aliasName: 'Other', members: [{ tagId: 'Value' }] }],
    }] })
    expect(generated).toEqual(before)
  })

  it('drops an empty generated parent once its only child is already covered', () => {
    const child = { kind: 'List', baseGroup: 'L.P.DB.S.Inner', aliasName: 'codes', members: [{ tagId: 'Code' }] }
    const result = createItemIdMapping({ fields: [], structs: [child] }, { fields: [], structs: [{ ...nested, members: [] }] }, group)
    expect(result).toEqual({ fields: [], structs: [child] })
  })

  it.each(['[0]', '_1'])('rejects partial generated-array overlaps at %s instead of dropping the manual structure', suffix => {
    const child = { kind: 'Object', baseGroup: `L.P.DB.Cells${suffix}`, aliasName: 'first', members: [{ tagId: 'Code' }] }
    const payload = { fields: [], structs: [child] }
    const generated = { fields: [], structs: [{ kind: 'Array', baseGroup: 'L.P.DB.Cells', aliasName: 'Cells', fixedCount: 2, members: [{ tagId: 'Code' }] }] }
    const before = structuredClone({ payload, generated })
    expect(() => createItemIdMapping(payload, generated, group)).toThrow(/重叠/)
    expect({ payload, generated }).toEqual(before)
  })

  it('keeps parameterDic item keys separate from outer structure aliases', () => {
    const structure = { kind: 'Object', baseGroup: 'L.P.DB.S', aliasName: 'L.P.DB.T', members: [{ tagId: 'A' }] }
    expect(createItemIdMapping({ fields: [field], structs: [structure] }, { fields: [field], structs: [] }, group))
      .toEqual({ fields: [field], structs: [structure] })
  })

  it.each([
    { append: { parameterDic: 'old' } },
    { fixedValues: [{ name: 'ParameterDic', dataType: 'Text', value: 'old' }] },
    { extraFields: [{ name: 'parameterDic.code', dataType: 'string', source: 'Fixed', value: 'old' }] },
    { structs: [{ kind: 'Object', baseGroup: 'L.P.DB.S', aliasName: 'parameterDic', members: [{ tagId: 'A' }] }] },
  ])('rejects outer fields that occupy the parameterDic container without mutating input: %j', extra => {
    const payload = { fields: [field], structs: [], ...extra }
    const before = structuredClone(payload)
    expect(() => createItemIdMapping(payload, { fields: [field], structs: [] }, group)).toThrow(/parameterDic/)
    expect(payload).toEqual(before)
  })

  it('rejects a generated scalar ancestor and colliding root aliases rather than introducing double output', () => {
    const child = { kind: 'List', baseGroup: 'L.P.DB.S.Inner', aliasName: 'S', members: [{ tagId: 'Code' }] }
    const payload = { fields: [], structs: [child] }
    expect(() => createItemIdMapping(payload, { fields: [{ tagId: 'L.P.DB.S' }], structs: [] }, group)).toThrow(/重叠/)
    expect(() => createItemIdMapping(payload, { fields: [], structs: [nested] }, group)).toThrow(/重叠/)
  })
})
